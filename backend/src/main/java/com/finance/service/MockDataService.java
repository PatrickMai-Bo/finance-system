    private List<String> moatTags(int moat, double gross) {
        List<String> tags = new ArrayList<>();
        if (gross >= 60) tags.add("品牌壁垒");
        if (moat >= 85) tags.add("规模成本壁垒");
        if (moat >= 80) tags.add("渠道壁垒");
        if (gross >= 50 && moat >= 80) tags.add("定价权强");
        if (tags.isEmpty()) tags.add("壁垒一般");
        return tags;
    }

    private List<String> indexMoatTags(String type) {
        switch (type) {
            case "指数基金": return Arrays.asList("底层龙头", "分散化");
            case "混合型": return Arrays.asList("经理选股", "主动管理");
            case "债券型": return Arrays.asList("票息现金流", "防御");
            case "货币基金": return Arrays.asList("流动性", "现金蓄水池");
            case "QDII": return Arrays.asList("海外配置", "汇率敞口");
            default: return Collections.singletonList("资产配置");
        }
    }

    private String rating(int score, double margin) {
        if (score >= 90 && margin >= 25) return "强烈推荐";
        if (score >= 80) return "推荐";
        if (score >= 65) return "观察";
        return "回避";
    }

    private String reason(String name, int peQ, double roe, double margin, int moat) {
        StringBuilder sb = new StringBuilder();
        sb.append("PE分位").append(peQ).append("%").append(peQ < 30 ? "(低估区)" : "(合理)");
        sb.append(",ROE ").append(roe).append("%").append(roe >= 15 ? "持续优异" : "偏弱");
        sb.append(",护城河评分").append(moat).append(moat >= 80 ? "(宽护城河)" : "");
        if (margin >= 30) sb.append(",安全边际充足(≥30%)");
        else if (margin > 0) sb.append(",安全边际不足30%需等待");
        else sb.append(",当前高于内在价值,不宜追高");
        return sb.toString();
    }

    private int[] fcfTrend(int seed) {
        int[] t = new int[10];
        int base = 30 + seed * 5;
        Random rnd = new Random(seed);
        for (int i = 0; i < 10; i++) {
            base += (int) (base * (0.05 + rnd.nextDouble() * 0.10)) - (seed > 9 ? rnd.nextInt(15) : 0);
            t[i] = Math.max(5, base);
        }
        return t;
    }
